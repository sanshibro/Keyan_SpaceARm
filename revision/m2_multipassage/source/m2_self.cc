// Native positive-distance support certificate. A failed convergence or
// overlapping simplex is rejected; no optimistic contact distance is returned.
#include <algorithm>
#include <array>
#include <cmath>
#include <vector>
using V=std::array<double,3>;
V add(V a,V b){for(int i=0;i<3;++i)a[i]+=b[i];return a;}
V sub(V a,V b){for(int i=0;i<3;++i)a[i]-=b[i];return a;}
V mul(V a,double s){for(double &x:a)x*=s;return a;}
double dot(V a,V b){return a[0]*b[0]+a[1]*b[1]+a[2]*b[2];}
double norm(V a){return std::sqrt(dot(a,a));}
struct Shapes {
 const int* type;const double *size,*pose,*verts;const int *offset,*count;
 double angle=0.;int robot_end=0;V pivot{0,0,0};
 V center(int i)const {return {pose[12*i],pose[12*i+1],pose[12*i+2]};}
 V raw_support(int i,V n)const {
  const double *r=pose+12*i+3,*h=size+3*i; V d{},p{};
  for(int k=0;k<3;++k)for(int j=0;j<3;++j)d[k]+=r[3*j+k]*n[j];
  double dn=std::max(1e-30,norm(d));
  if(type[i]==7) { double best=-1e300;for(int k=0;k<count[i];++k){const double *v=verts+3*(offset[i]+k);double s=v[0]*d[0]+v[1]*d[1]+v[2]*d[2];if(s>best){best=s;p={v[0],v[1],v[2]};}} }
  else if(type[i]==6)for(int k=0;k<3;++k)p[k]=h[k]*(d[k]>=0?1:-1);
  else if(type[i]==2||type[i]==3){p=mul(d,h[0]/dn);if(type[i]==3)p[2]+=h[1]*(d[2]>=0?1:-1);}
  else if(type[i]==5){double rxy=std::max(1e-30,std::hypot(d[0],d[1]));p={h[0]*d[0]/rxy,h[0]*d[1]/rxy,h[1]*(d[2]>=0?1:-1)};}
  else if(type[i]==4){double den=std::max(1e-30,std::sqrt(h[0]*h[0]*d[0]*d[0]+h[1]*h[1]*d[1]*d[1]+h[2]*h[2]*d[2]*d[2]));for(int k=0;k<3;++k)p[k]=h[k]*h[k]*d[k]/den;}
  V out=center(i);for(int k=0;k<3;++k)for(int j=0;j<3;++j)out[k]+=r[3*k+j]*p[j];return out;
 }
 V rotated_point(V point,V n)const {
  // A complete horizontal-axis (roll/pitch) rotation disc. Rodrigues gives
  // Rv = v + sin(a)*(k x v) + (1-cos(a))*k x (k x v). The first displacement
  // lies in an ellipse generated by horizontal k; the remainder lies in a
  // ball of radius (1-cos(angle))*|v|. Their Minkowski sum is a certified
  // continuous superset, without erroneously adding yaw uncertainty.
  V v=sub(point,pivot);double length=norm(v),nn=norm(n);if(length<1e-15||nn<1e-15)return point;
  V cross{v[1]*n[2]-v[2]*n[1],v[2]*n[0]-v[0]*n[2],0.};double cn=norm(cross);
  V k=cn>1e-30?mul(cross,1./cn):V{1,0,0};V first{k[1]*v[2],-k[0]*v[2],k[0]*v[1]-k[1]*v[0]};
  return add(point,add(mul(first,std::sin(angle)),mul(n,(1-std::cos(angle))*length/nn)));
 }
 V support(int i,V n)const {
  if(angle<=0||i>=robot_end)return raw_support(i,n);
  const double *r=pose+12*i+3,*h=size+3*i;V c=center(i);double best=-1e300;V selected=c;
  auto visit=[&](V p){V world=c;for(int k=0;k<3;++k)for(int j=0;j<3;++j)world[k]+=r[3*k+j]*p[j];
    V q=rotated_point(world,n);double score=dot(q,n);if(score>best){best=score;selected=q;}};
  if(type[i]==7){for(int j=0;j<count[i];++j){const double*v=verts+3*(offset[i]+j);visit({v[0],v[1],v[2]});}}
  else if(type[i]==6){for(int k=0;k<8;++k)visit({h[0]*(k&1?1:-1),h[1]*(k&2?1:-1),h[2]*(k&4?1:-1)});}
  else if(type[i]==2||type[i]==3){if(type[i]==3){visit({0,0,h[1]});visit({0,0,-h[1]});}else visit({0,0,0});selected=add(selected,mul(n,h[0]/std::max(1e-30,norm(n))));}
  else if(type[i]==5){const int N=32;double radius=h[0]/std::cos(M_PI/N);for(int j=0;j<N;++j)for(int sgn:{-1,1}){double phi=2*M_PI*j/N;visit({radius*std::cos(phi),radius*std::sin(phi),sgn*h[1]});}}
  else {visit({0,0,0});selected=add(selected,mul(n,std::max({h[0],h[1],h[2]})/std::max(1e-30,norm(n))));}
  return selected;
 }
};
bool solve(double a[5][6],int n,double* x){
 for(int k=0;k<n;++k){int p=k;for(int j=k+1;j<n;++j)if(std::abs(a[j][k])>std::abs(a[p][k]))p=j;
  if(std::abs(a[p][k])<1e-17)return false;for(int j=k;j<=n;++j)std::swap(a[p][j],a[k][j]);
  double v=a[k][k];for(int j=k;j<=n;++j)a[k][j]/=v;
  for(int i=0;i<n;++i)if(i!=k){v=a[i][k];for(int j=k;j<=n;++j)a[i][j]-=v*a[k][j];}
 }for(int i=0;i<n;++i)x[i]=a[i][n];return true;
}
V closest(std::vector<V>& s){
 double best=1e300;V point{};std::vector<V> kept;int N=(int)s.size();
 for(int mask=1;mask<(1<<N);++mask){int ids[5],n=0;for(int i=0;i<N;++i)if(mask&(1<<i))ids[n++]=i;
  if(n>4)continue;double weights[5]={};bool ok=true;
  if(n==1)weights[0]=1;else {double a[5][6]={};for(int i=0;i<n;++i){for(int j=0;j<n;++j)a[i][j]=2*dot(s[ids[i]],s[ids[j]]);a[i][n]=1;a[n][i]=1;}a[n][n+1]=1;ok=solve(a,n+1,weights);}
  if(!ok)continue;V q{};for(int i=0;i<n;++i){if(weights[i]<-1e-8)ok=false;q=add(q,mul(s[ids[i]],weights[i]));}
  if(!ok)continue;double distance=dot(q,q);if(distance<best){best=distance;point=q;kept.clear();for(int i=0;i<n;++i)if(weights[i]>1e-10)kept.push_back(s[ids[i]]);}
 }s=kept;return point;
}
std::array<double,3> distance(const Shapes& s,int a,int b,double tolerance){
 auto support=[&](V n){return sub(s.support(a,n),s.support(b,mul(n,-1)));};
 V d=sub(s.center(a),s.center(b));if(norm(d)<1e-15)d={1,0,0};std::vector<V> simplex{support(mul(d,-1))};V v=simplex[0];
 double lower=-1e300,upper=norm(v);int it=0;
 for(;it<96;++it){upper=norm(v);if(upper<1e-12)return {-1.,0.,double(it)};
  V w=support(mul(v,-1));lower=std::max(lower,dot(v,w)/upper);
  if(upper-lower<=tolerance)return {lower,upper,double(it)};
  bool duplicate=false;for(auto z:simplex)if(norm(sub(z,w))<1e-12)duplicate=true;
  if(duplicate)break;simplex.push_back(w);v=closest(simplex);if(simplex.empty())break;
 }return {lower,upper,double(it)};
}
void scan(const Shapes&s,int n,const double*pose,const double*aabb,int np,const int*pairs,double tol,double*out,int*which){
 std::vector<V>lo(n),hi(n);
 for(int i=0;i<n;++i){V c=s.center(i),h{};const double*r=pose+12*i+3;for(int k=0;k<3;++k)for(int j=0;j<3;++j){c[k]+=r[3*k+j]*aabb[6*i+j];h[k]+=std::abs(r[3*k+j])*aabb[6*i+3+j];}
  if(s.angle>0&&i<s.robot_end){double reserve=(std::sin(s.angle)+1-std::cos(s.angle))*(norm(sub(c,s.pivot))+norm(h));if(s.type[i]==5)reserve+=s.size[3*i]*(1/std::cos(M_PI/32)-1);for(double&x:h)x+=reserve;}
  lo[i]=sub(c,h);hi[i]=add(c,h);}
 std::vector<std::pair<double,int>> order;order.reserve(np);
 for(int k=0;k<np;++k){int a=pairs[2*k],b=pairs[2*k+1];V delta{};for(int j=0;j<3;++j)delta[j]=std::max(0.,std::max(lo[a][j]-hi[b][j],lo[b][j]-hi[a][j]));order.emplace_back(norm(delta),k);}
 std::sort(order.begin(),order.end());double lower=1e300,upper=1e300;int tested=0,iterations=0;
 for(auto item:order){if(item.first>upper)break;int k=item.second,a=pairs[2*k],b=pairs[2*k+1];auto r=distance(s,a,b,tol);tested++;iterations+=(int)r[2];lower=std::min(lower,r[0]);if(r[1]<upper){upper=r[1];which[0]=a;which[1]=b;}if(upper<=0)break;}
 out[0]=lower;out[1]=upper;out[2]=tested;out[3]=iterations;
}
extern "C" void self_clearance(int n,const int*type,const double*size,const double*pose,const double*aabb,
 const int*offset,const int*count,const double*verts,int np,const int*pairs,double tol,double*out,int*which){
 Shapes s{type,size,pose,verts,offset,count};scan(s,n,pose,aabb,np,pairs,tol,out,which);
}
extern "C" void external_robust_clearance(int n,const int*type,const double*size,const double*pose,const double*aabb,
 const int*offset,const int*count,const double*verts,int np,const int*pairs,double tol,int robot_end,double angle,const double*pivot,double*out,int*which){
 Shapes s{type,size,pose,verts,offset,count};s.angle=angle;s.robot_end=robot_end;s.pivot={pivot[0],pivot[1],pivot[2]};scan(s,n,pose,aabb,np,pairs,tol,out,which);
}
